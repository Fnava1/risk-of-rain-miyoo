/* On Miyoo Mini Plus, LCD is mounted upside down (180 degrees inverted) */
static inline void set_pixel(int x, int y, uint8_t r, uint8_t g, uint8_t b) {
    if (x < 0 || x >= s_fb_width || y < 0 || y >= s_fb_height || !s_fb_ptr) {
        return;
    }

    int inv_x = (s_fb_width - 1) - x;
    int inv_y = (s_fb_height - 1) - y;

    if (s_fb_bpp == 16) {
        uint16_t *dst = (uint16_t *)(s_fb_ptr + inv_y * s_fb_line_len + inv_x * 2);
        *dst = (uint16_t)(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3));
    } else if (s_fb_bpp == 32) {
        uint32_t *dst = (uint32_t *)(s_fb_ptr + inv_y * s_fb_line_len + inv_x * 4);
        *dst = (0xFF000000u) | ((uint32_t)r << 16) | ((uint32_t)g << 8) | (uint32_t)b;
    }
}

static void fill_rect(int x, int y, int w, int h, uint8_t r, uint8_t g, uint8_t b) {
    for (int j = y; j < y + h; ++j) {
        for (int i = x; i < x + w; ++i) {
            set_pixel(i, j, r, g, b);
        }
    }
}

static void draw_char(int x, int y, char c, int scale, uint8_t r, uint8_t g, uint8_t b) {
    if (c < 32 || c > 126) c = ' ';
    const uint8_t *glyph = s_font8x8[c - 32];
    for (int row = 0; row < 8; ++row) {
        uint8_t line = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if (line & (0x80 >> col)) {
                if (scale == 1) {
                    set_pixel(x + col, y + row, r, g, b);
                } else {
                    for (int dy = 0; dy < scale; ++dy) {
                        for (int dx = 0; dx < scale; ++dx) {
                            set_pixel(x + col * scale + dx, y + row * scale + dy, r, g, b);
                        }
                    }
                }
            }
        }
    }
}

static void draw_string(int x, int y, const char *str, int scale, uint8_t r, uint8_t g, uint8_t b) {
    if (!str) return;
    int cur_x = x;
    while (*str) {
        draw_char(cur_x, y, *str, scale, r, g, b);
        cur_x += 8 * scale;
        str++;
    }
}

int fb_progress_init(void) {
    s_fb_fd = open("/dev/fb0", O_RDWR);
    if (s_fb_fd < 0) {
        s_fb_active = 0;
        printf("[SETUP] Notice: /dev/fb0 unavailable (using console mode)\n");
        return 0;
    }

    struct fb_var_screeninfo vinfo;
    struct fb_fix_screeninfo finfo;

    if (ioctl(s_fb_fd, FBIOGET_VSCREENINFO, &vinfo) < 0 ||
        ioctl(s_fb_fd, FBIOGET_FSCREENINFO, &finfo) < 0) {
        close(s_fb_fd);
        s_fb_fd = -1;
        s_fb_active = 0;
        printf("[SETUP] Notice: Unable to query framebuffer info\n");
        return 0;
    }

    s_fb_width = vinfo.xres;
    s_fb_height = vinfo.yres;
    s_fb_bpp = vinfo.bits_per_pixel;
    s_fb_line_len = finfo.line_length;
    s_fb_size = finfo.smem_len;

    if (s_fb_bpp != 16 && s_fb_bpp != 32) {
        close(s_fb_fd);
        s_fb_fd = -1;
        s_fb_active = 0;
        printf("[SETUP] Unsupported framebuffer depth: %d bpp\n", s_fb_bpp);
        return 0;
    }

    s_fb_ptr = (uint8_t *)mmap(NULL, s_fb_size, PROT_READ | PROT_WRITE, MAP_SHARED, s_fb_fd, 0);
    if (s_fb_ptr == MAP_FAILED) {
        s_fb_ptr = NULL;
        close(s_fb_fd);
        s_fb_fd = -1;
        s_fb_active = 0;
        printf("[SETUP] Failed to mmap /dev/fb0\n");
        return 0;
    }

    s_fb_active = 1;

    // Background: Deep dark slate / charcoal
    fill_rect(0, 0, s_fb_width, s_fb_height, 16, 20, 24);

    // Title rendering
    const char *title = "RISK OF RAIN";
    int title_x = (s_fb_width - ((int)strlen(title) * 8 * 2)) / 2;
    draw_string(title_x, 140, title, 2, 230, 200, 110); // Gold/amber text

    const char *sub = "Configuracion Inicial de Archivos...";
    int sub_x = (s_fb_width - ((int)strlen(sub) * 8)) / 2;
    draw_string(sub_x, 185, sub, 1, 170, 180, 195);

    return 0;
}

int fb_progress_is_fb_active(void) {
    return s_fb_active;
}

void fb_progress_update(float progress, const char *status_text) {
    if (progress < 0.0f) progress = 0.0f;
    if (progress > 1.0f) progress = 1.0f;

    int pct = (int)(progress * 100.0f);
    printf("\r[Miyoo Setup %3d%%] %s", pct, status_text ? status_text : "");
    fflush(stdout);

    if (!s_fb_active || !s_fb_ptr) return;

    int bar_w = 460;
    int bar_h = 24;
    int bar_x = (s_fb_width - bar_w) / 2;
    int bar_y = 230;

    // Border (soft gray)
    fill_rect(bar_x - 2, bar_y - 2, bar_w + 4, bar_h + 4, 60, 70, 80);
    // Background trough (darker gray)
    fill_rect(bar_x, bar_y, bar_w, bar_h, 30, 36, 44);

    // Filled portion (amber/orange RoR theme)
    int fill_w = (int)((float)bar_w * progress);
    if (fill_w > 0) {
        fill_rect(bar_x, bar_y, fill_w, bar_h, 220, 150, 40);
    }

    // Status text line: clear text area and redraw
    fill_rect(40, 280, s_fb_width - 80, 24, 16, 20, 24);
    if (status_text) {
        char buf[80];
        snprintf(buf, sizeof(buf), "[%d%%] %s", pct, status_text);
        int text_x = (s_fb_width - ((int)strlen(buf) * 8)) / 2;
        if (text_x < 20) text_x = 20;
        draw_string(text_x, 280, buf, 1, 210, 215, 225);
    }
}

void fb_progress_show_error(const char *title, const char *line1, const char *line2, const char *line3) {
    printf("\n[ERROR] %s\n  %s\n  %s\n  %s\n", title ? title : "", line1 ? line1 : "", line2 ? line2 : "", line3 ? line3 : "");
    if (!s_fb_active || !s_fb_ptr) return;

    // Clear whole screen to dark maroon/red
    fill_rect(0, 0, s_fb_width, s_fb_height, 35, 12, 14);

    if (title) {
        int tx = (s_fb_width - ((int)strlen(title) * 8 * 2)) / 2;
        draw_string(tx, 120, title, 2, 255, 90, 90);
    }
    if (line1) {
        int lx = (s_fb_width - ((int)strlen(line1) * 8)) / 2;
        draw_string(lx, 190, line1, 1, 240, 240, 240);
    }
    if (line2) {
        int lx = (s_fb_width - ((int)strlen(line2) * 8)) / 2;
        draw_string(lx, 215, line2, 1, 240, 240, 240);
    }
    if (line3) {
        int lx = (s_fb_width - ((int)strlen(line3) * 8)) / 2;
        draw_string(lx, 245, line3, 1, 180, 180, 190);
    }
}

void fb_progress_close(void) {
    if (s_fb_ptr && s_fb_ptr != MAP_FAILED) {
        memset(s_fb_ptr, 0, s_fb_size);
        munmap(s_fb_ptr, s_fb_size);
        s_fb_ptr = NULL;
    }
    if (s_fb_fd >= 0) {
        close(s_fb_fd);
        s_fb_fd = -1;
    }
    s_fb_active = 0;
}
