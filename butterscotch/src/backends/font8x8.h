static inline void font8x8_draw_char(uint16_t *fb, int tw, int th, int x, int y, char c, uint16_t color, int scale) {
    if (c < 32 || c > 126 || !fb) return;
    const uint8_t *glyph = s_font8x8[(int)(c - 32)];
    if (scale <= 1) {
        for (int r = 0; r < 8; r++) {
            int py = y + r;
            if (py < 0 || py >= th) continue;
            uint8_t row = glyph[r];
            for (int col = 0; col < 8; col++) {
                int px = x + col;
                if (px < 0 || px >= tw) continue;
                if (row & (0x80 >> col)) {
                    fb[py * tw + px] = color;
                }
            }
        }
    } else {
        for (int r = 0; r < 8; r++) {
            uint8_t row = glyph[r];
            for (int col = 0; col < 8; col++) {
                if (row & (0x80 >> col)) {
                    for (int dy = 0; dy < scale; dy++) {
                        int py = y + r * scale + dy;
                        if (py < 0 || py >= th) continue;
                        for (int dx = 0; dx < scale; dx++) {
                            int px = x + col * scale + dx;
                            if (px < 0 || px >= tw) continue;
                            fb[py * tw + px] = color;
                        }
                    }
                }
            }
        }
    }
}

static inline void font8x8_draw_string(uint16_t *fb, int tw, int th, int x, int y, const char *str, uint16_t color, int scale) {
    if (!str || !fb) return;
    int cur_x = x;
    while (*str) {
        font8x8_draw_char(fb, tw, th, cur_x, y, *str, color, scale);
        cur_x += 8 * (scale > 1 ? scale : 1);
        str++;
    }
}

